import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# PARÁMETROS DEL CIRCUITO DE LTSPICE
# ============================================================

Rser = 50

# ------------------------------------------------------------
# RLC 1
# ------------------------------------------------------------

R1 = 9875.1012
L1 = 578.8034
C1 = 0.0174383e-12

# ------------------------------------------------------------
# RLC 2
# ------------------------------------------------------------

R2_RLC = 50000
L2 = 400
C2_RLC = 0.0150e-12

# ------------------------------------------------------------
# RLC 3
# ------------------------------------------------------------

R3_RLC = 100000
L3 = 300
C3_RLC = 0.0130e-12

# ------------------------------------------------------------
# RLC 4
# ------------------------------------------------------------

R4_RLC = 150000
L4 = 200
C4_RLC = 0.0110e-12


# ============================================================
# IMPEDANCIAS ADICIONALES DEL CIRCUITO
# ============================================================

# Carga de salida
Rload = 10e3
Cload = 145e-12

# Impedancia de entrada
Rin = 10e3
Cin = 144e-12


# ============================================================
# FRECUENCIA
# ============================================================

f = np.linspace(49.5e3, 120e3, 1000000)

w = 2*np.pi*f

j = 1j


# ============================================================
# IMPEDANCIAS DE LAS CUATRO RAMAS RLC
# ============================================================

# RLC 1
Z1 = R1 + j*w*L1 + 1/(j*w*C1)

# RLC 2
Z2 = R2_RLC + j*w*L2 + 1/(j*w*C2_RLC)

# RLC 3
Z3 = R3_RLC + j*w*L3 + 1/(j*w*C3_RLC)

# RLC 4
Z4 = R4_RLC + j*w*L4 + 1/(j*w*C4_RLC)


# ============================================================
# PARALELO DE LAS CUATRO RAMAS RLC
#
# Zp = Z1 || Z2 || Z3 || Z4
# ============================================================

Yp = (
    1/Z1
    + 1/Z2
    + 1/Z3
    + 1/Z4
)

Zp = 1/Yp


# ============================================================
# IMPEDANCIA DE CARGA DE SALIDA
#
# Rload || Cload
# ============================================================

ZL = 1/(1/Rload + j*w*Cload)


# ============================================================
# IMPEDANCIA DE ENTRADA
#
# Rin || Cin
# ============================================================

Zin = 1/(1/Rin + j*w*Cin)


# ============================================================
# RAMA DESDE EL NODO DE ENTRADA HASTA TIERRA
#
# Zp + ZL
# ============================================================

Zrama = Zp + ZL


# ============================================================
# IMPEDANCIA TOTAL VISTA POR Rser
#
# Zin || (Zp + ZL)
# ============================================================

Ztotal = 1/(1/Zin + 1/Zrama)


# ============================================================
# TENSIÓN EN EL NODO DE ENTRADA
#
# Vin / Vsource
# ============================================================

Vin = Ztotal/(Rser + Ztotal)


# ============================================================
# DIVISOR ENTRE Zp Y ZL
#
# Vout / Vin
# ============================================================

Vout_Vin = ZL/(Zp + ZL)


# ============================================================
# TRANSFERENCIA TOTAL
#
# H = Vout / Vsource
# ============================================================

H = Vin * Vout_Vin


# ============================================================
# MÓDULO Y FASE
# ============================================================

modulo_H = np.abs(H)

fase_H = np.angle(H, deg=True)


# ============================================================
# GRÁFICA DEL MÓDULO
# ============================================================

plt.figure(figsize=(10,6))

plt.semilogy(f, modulo_H)

plt.xlabel("Frecuencia (Hz)")
plt.ylabel("|H|")
plt.title("Módulo de H = Vout / Vsource")

plt.grid(True, which="both", ls="--")

plt.xlim(49.5e3, 120e3)

plt.show()


# ============================================================
# GRÁFICA DE LA FASE
# ============================================================

plt.figure(figsize=(10,6))

plt.plot(f, fase_H)

plt.xlabel("Frecuencia (Hz)")
plt.ylabel("Fase (°)")
plt.title("Argumento de H = Vout / Vsource")

plt.grid(True, which="both", ls="--")

plt.xlim(49.5e3, 120e3)

plt.show()


# ============================================================
# NYQUIST
# ============================================================

plt.figure(figsize=(8, 8))

# Curva coloreada según frecuencia
sc = plt.scatter(
    H.real,
    H.imag,
    c=f/1e3,          # frecuencia en kHz
    cmap='viridis',
    s=3
)

# Barra de color
cbar = plt.colorbar(sc)

cbar.set_label("Frecuencia (kHz)")

# Ejes
plt.xlabel("Re(H)")
plt.ylabel("Im(H)")

plt.title("Plano complejo de H")

plt.grid(True)

plt.axis("equal")

plt.show()